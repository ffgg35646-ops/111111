export function getPlatformCourseQuiz(trackId: string, custom?: PlatformQuizQuestion[] | null) {
  return Array.isArray(custom) && custom.length >= 3
    ? custom
    : platformQuizByTrack[trackId] || platformQuizByTrack["mental-health"];
}

export function scorePlatformCourseQuiz(
  trackId: string,
  answers: Record<string, unknown>,
  checked: boolean,
  custom?: PlatformQuizQuestion[] | null,
) {
  const questions = getPlatformCourseQuiz(trackId, custom);
  const score = questions.reduce(
    (total, question, index) => total + (answers[String(index)] === question.correct ? 1 : 0),
    0,
  );
  const passMark = Math.ceil(questions.length * (2 / 3));
  return { score, total: questions.length, passMark, passed: checked && score >= passMark };
}
